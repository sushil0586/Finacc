    @staticmethod
    def _gstin_for_target(target: TenantTarget) -> str:
        number = sum((idx + 1) * ord(ch) for idx, ch in enumerate(target.code)) % 10000
        suffix = target.code[-1] if target.code[-1].isalpha() else "X"
        pan = f"PF{suffix}AB{number:04d}C"
        return f"27{pan}1Z5"

    def _account(self, entity, head, code, suffix, actor, partytype, gstin):
        ledger, _ = Ledger.objects.get_or_create(entity=entity, ledger_code=code, defaults={"name": suffix, "accounthead": head, "createdby": actor})
        acc = getattr(ledger, "account_profile", None)
        if acc is None:
            acc = create_account_with_synced_ledger(
                account_data={"entity": entity, "ledger": ledger, "accountname": suffix, "createdby": actor},
                ledger_overrides={"ledger_code": code, "accounthead": head, "is_party": bool(partytype)},
            )
        if partytype:
            AccountCommercialProfile.objects.update_or_create(account=acc, defaults={"entity": entity, "partytype": partytype, "createdby": actor})
            AccountComplianceProfile.objects.update_or_create(account=acc, defaults={"entity": entity, "gstno": gstin, "pan": gstin[2:12], "createdby": actor})
        return acc

    def _numbering(self, entity, entityfin, subentity, module, doc_key, doc_code, prefix, actor):
        doc_type, _ = DocumentType.objects.get_or_create(module=module, doc_key=doc_key, defaults={"name": doc_key, "default_code": doc_code, "is_active": True})
        DocumentNumberSeries.objects.get_or_create(
            entity=entity,
            entityfinid=entityfin,
            subentity=subentity,
            doc_type=doc_type,
            doc_code=doc_code,
            defaults={"prefix": prefix, "starting_number": 1, "current_number": 1, "is_active": True, "created_by": actor},
        )

    def _seed_tenant(self, *, tenant, target: TenantTarget, batch_size: int, rng: random.Random, payment_ratio: Decimal) -> dict:
        sales_inserted = self._seed_sales(tenant, target.sales, batch_size, rng, payment_ratio)
        purchase_inserted = self._seed_purchase(tenant, target.purchase, batch_size, rng, payment_ratio)
        return {"tenant": target.code, "entity_id": tenant["entity"].id, "sales_inserted": sales_inserted, "purchase_inserted": purchase_inserted}

    def _seed_sales(self, tenant, total: int, batch_size: int, rng: random.Random, payment_ratio: Decimal) -> int:
        inserted = 0
        existing = SalesInvoiceHeader.objects.filter(entity=tenant["entity"], legacy_source_system="phase2b3b").count()
        for start in range(existing + 1, total + 1, batch_size):
            end = min(start + batch_size - 1, total)
            with transaction.atomic():
                for n in range(start, end + 1):
                    bill_date = date(2026, 4, 1) + timedelta(days=rng.randrange(180))
                    due_date = bill_date + timedelta(days=30)
                    paid = TOTAL if Decimal(n % 10) / Decimal("10") < payment_ratio else ZERO
                    header = SalesInvoiceHeader.objects.create(
                        entity=tenant["entity"], entityfinid=tenant["entityfin"], subentity=tenant["subentity"],
                        doc_type=SalesInvoiceHeader.DocType.TAX_INVOICE, status=SalesInvoiceHeader.Status.POSTED,
                        bill_date=bill_date, posting_date=bill_date, due_date=due_date, credit_days=30,
                        doc_code="SINV", doc_no=n, invoice_number=f"{tenant['target'].code}-SINV-{n:06d}",
                        customer=tenant["customer"], customer_ledger=tenant["customer"].ledger,
                        customer_name=tenant["customer"].accountname, customer_gstin="27VWXYZ1234F1Z5",
                        customer_state_code="27", seller_gstin="27AAAAA1234A1Z5", seller_state_code="27",
                        place_of_supply_state_code="29", supply_category=SalesInvoiceHeader.SupplyCategory.DOMESTIC_B2B,
                        taxability=SalesInvoiceHeader.Taxability.TAXABLE, tax_regime=SalesInvoiceHeader.TaxRegime.INTER_STATE,
                        is_igst=True, total_taxable_value=TAXABLE, total_igst=GST, grand_total=TOTAL,
                        settled_amount=paid, outstanding_amount=TOTAL - paid,
                        settlement_status=SalesInvoiceHeader.SettlementStatus.SETTLED if paid == TOTAL else SalesInvoiceHeader.SettlementStatus.OPEN,
                        reference=f"P2B3B-S-{n}", posted_at=timezone.now(), posted_by=tenant["actor"],
                        legacy_source_system="phase2b3b", legacy_source_key=f"{tenant['target'].code}:sales:{n}",
                    )
                    SalesInvoiceLine.objects.create(entity=tenant["entity"], entityfinid=tenant["entityfin"], subentity=tenant["subentity"], header=header, line_no=1, productDesc="Performance service", hsn_sac_code="998311", is_service=True, qty=1, rate=TAXABLE, taxability=SalesInvoiceHeader.Taxability.TAXABLE, gst_rate=18, igst_amount=GST, taxable_value=TAXABLE, line_total=TOTAL, sales_account=tenant["sales"])
                    SalesTaxSummary.objects.create(entity=tenant["entity"], entityfinid=tenant["entityfin"], subentity=tenant["subentity"], header=header, taxability=SalesInvoiceHeader.Taxability.TAXABLE, hsn_sac_code="998311", is_service=True, gst_rate=18, taxable_value=TAXABLE, igst_amount=GST)
                    CustomerBillOpenItem.objects.create(header=header, entity=tenant["entity"], entityfinid=tenant["entityfin"], subentity=tenant["subentity"], customer=tenant["customer"], customer_ledger=tenant["customer"].ledger, doc_type=header.doc_type, bill_date=bill_date, due_date=due_date, invoice_number=header.invoice_number, original_amount=TOTAL, gross_amount=TOTAL, net_receivable_amount=TOTAL, settled_amount=paid, outstanding_amount=TOTAL - paid, is_open=paid < TOTAL)
                    if paid:
                        settlement = CustomerSettlement.objects.create(entity=tenant["entity"], entityfinid=tenant["entityfin"], subentity=tenant["subentity"], customer=tenant["customer"], customer_ledger=tenant["customer"].ledger, settlement_type=CustomerSettlement.SettlementType.RECEIPT, settlement_date=bill_date, reference_no=f"RCPT-{header.doc_no}", total_amount=paid, status=CustomerSettlement.Status.POSTED, posted_at=timezone.now(), posted_by=tenant["actor"])
                        CustomerSettlementLine.objects.create(settlement=settlement, open_item=header.ap_open_item, amount=paid, applied_amount_signed=paid)
                    self._post_entry(tenant, TxnType.SALES, header.id, header.invoice_number, bill_date, [(tenant["customer"], True, TOTAL), (tenant["sales"], False, TAXABLE), (tenant["output_igst"], False, GST)])
                    inserted += 1
        return inserted

