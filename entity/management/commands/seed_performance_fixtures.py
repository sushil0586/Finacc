ZERO = Decimal("0.00")
TAXABLE = Decimal("500.00")
GST = Decimal("90.00")
TOTAL = Decimal("590.00")


@dataclass
class TenantTarget:
    code: str
    label: str
    sales: int
    purchase: int


class Command(BaseCommand):
    help = "Seed deterministic, isolated multi-tenant performance fixtures after staging safety gates pass."

    def add_arguments(self, parser):
        parser.add_argument("--profile", choices=["tiny", "small", "medium", "large"], default="tiny")
        parser.add_argument("--sales", type=int, default=None, help="Override sales invoice count per tenant.")
        parser.add_argument("--purchase", type=int, default=None, help="Override purchase invoice count per tenant.")
        parser.add_argument("--batch-size", type=int, default=500)
        parser.add_argument("--seed", type=int, default=20261010)
        parser.add_argument("--payment-ratio", type=float, default=0.20)
        parser.add_argument("--json", action="store_true")
        parser.add_argument("--dry-run", action="store_true")
        parser.add_argument("--reset-fixture", action="store_true", help="Delete only rows generated by this command after safety audit passes.")
        parser.add_argument("--allow-db-name", action="append", default=[])
        parser.add_argument("--allow-db-host", action="append", default=[])

    def handle(self, *args, **options):
        started = time.perf_counter()
        self._assert_safety(options)
        targets = self._targets(options)
        rng = random.Random(int(options["seed"]))

        if options["reset_fixture"]:
            reset = self._reset_fixture(dry_run=options["dry_run"])
            self._write({"dry_run": options["dry_run"], "reset": reset}, options)
            return

        before = self._database_snapshot()
        if options["dry_run"]:
            payload = {
                "dry_run": True,
                "targets": [asdict(target) for target in targets],
                "database": before,
                "message": "Safety audit passed. No rows were written.",
            }
            self._write(payload, options)
            return

        results = []
        for target in targets:
            with transaction.atomic():
                tenant = self._ensure_tenant(target)
            result = self._seed_tenant(tenant=tenant, target=target, batch_size=options["batch_size"], rng=rng, payment_ratio=Decimal(str(options["payment_ratio"])))
            validation = self._validate_tenant(tenant)
            results.append({**result, "validation": validation})

        after = self._database_snapshot()
        payload = {
            "dry_run": False,
            "elapsed_seconds": round(time.perf_counter() - started, 3),
            "database_before": before,
            "database_after": after,
            "targets": [asdict(target) for target in targets],
            "results": results,
        }
        self._write(payload, options)

    def _assert_safety(self, options):
        out = StringIO()
        args = ["--json", "--strict"]
        for name in options["allow_db_name"]:
            args.extend(["--allow-db-name", name])
        for host in options["allow_db_host"]:
            args.extend(["--allow-db-host", host])
        try:
            call_command("audit_performance_staging", *args, stdout=out)
        except CommandError as exc:
            raise CommandError(f"Performance fixture seeding blocked by safety audit: {exc}") from exc
        payload = json.loads(out.getvalue())
        if not payload.get("ready"):
            raise CommandError("Performance fixture seeding blocked because staging audit is not ready.")

    def _targets(self, options) -> list[TenantTarget]:
        defaults = {
            "tiny": (4, 3),
            "small": (1000, 500),
            "medium": (10000, 5000),
            "large": (50000, 25000),
        }
        sales, purchase = defaults[options["profile"]]
        sales = int(options["sales"] if options["sales"] is not None else sales)
        purchase = int(options["purchase"] if options["purchase"] is not None else purchase)
        if sales < 0 or purchase < 0:
            raise CommandError("Sales and purchase counts must be non-negative.")
        return [
            TenantTarget(code=f"P2B3B-{options['profile'].upper()}-S", label=f"Phase2B3B {options['profile']} Small Tenant", sales=sales, purchase=purchase),
            TenantTarget(code=f"P2B3B-{options['profile'].upper()}-M", label=f"Phase2B3B {options['profile']} Medium Tenant", sales=sales, purchase=purchase),
            TenantTarget(code=f"P2B3B-{options['profile'].upper()}-L", label=f"Phase2B3B {options['profile']} Large Tenant", sales=sales, purchase=purchase),
        ]

    def _ensure_user(self):
        return User.objects.get_or_create(
            email="perf-fixture@local.invalid",
            defaults={"username": "perf-fixture", "is_active": True},
        )[0]

